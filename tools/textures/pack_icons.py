"""Packs renders into one sheet with a dark sticker outline, and writes the
lookup table the game uses.

    python3 tools/textures/pack_icons.py <render_dir>
        icon_*.png  -> assets/textures/ui/icons.png + Config/IconAtlas.luau
    python3 tools/textures/pack_icons.py <render_dir> pet_ pets PetIconAtlas 128 8
        pet_*.png   -> assets/textures/ui/pets.png  + Config/PetIconAtlas.luau
    python3 tools/textures/pack_icons.py <render_dir> icon_ icons IconAtlas 170 6 flat
        icons that already have outlines (Gvesster pack, tools/textures/vector_icons.py)

More images than fit one 1024 sheet spill onto <sheet>2.png, <sheet>3.png...
(Config/UiImages needs an id for each sheet).
"""

import glob
import os
import sys

from PIL import Image, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "../.."))
ARGS = sys.argv[1:]
PREFIX = ARGS[1] if len(ARGS) > 1 else "icon_"
SHEET = ARGS[2] if len(ARGS) > 2 else "icons"
LUA = ARGS[3] if len(ARGS) > 3 else "IconAtlas"
CELL = int(ARGS[4]) if len(ARGS) > 4 else 170
COLS = int(ARGS[5]) if len(ARGS) > 5 else 6
FLAT = len(ARGS) > 6 and ARGS[6] == "flat"  # images already carry their outline
OUTLINE = (28, 26, 38, 255)


def outlined(path):
    img = Image.open(path).convert("RGBA")
    # Crop to the drawn pixels, then fit the cell (keeping aspect, centred).
    box = img.split()[3].point(lambda a: 255 if a > 8 else 0).getbbox()
    if box:
        img = img.crop(box)
    inner = CELL - (4 if FLAT else max(8, CELL // 12))
    k = inner / max(img.size)
    img = img.resize((max(1, round(img.width * k)), max(1, round(img.height * k))), Image.LANCZOS)
    canvas = Image.new("RGBA", (CELL, CELL), (0, 0, 0, 0))
    canvas.paste(img, ((CELL - img.width) // 2, (CELL - img.height) // 2))
    if FLAT:
        return canvas
    alpha = canvas.split()[3].point(lambda a: 255 if a > 90 else 0)
    ring = alpha.filter(ImageFilter.MaxFilter(7)).filter(ImageFilter.GaussianBlur(0.8))
    back = Image.new("RGBA", canvas.size, OUTLINE)
    back.putalpha(ring)
    return Image.alpha_composite(back, canvas)


def main():
    renders = sorted(glob.glob(os.path.join(ARGS[0], f"{PREFIX}*.png")))
    names = [os.path.basename(p)[len(PREFIX):-4] for p in renders]
    per_sheet = COLS * (1024 // CELL)
    sheets = []
    for start in range(0, len(renders), per_sheet):
        sheet = Image.new("RGBA", (1024, 1024), (0, 0, 0, 0))
        for i, path in enumerate(renders[start : start + per_sheet]):
            sheet.paste(outlined(path), ((i % COLS) * CELL, (i // COLS) * CELL))
        name = SHEET if not sheets else f"{SHEET}{len(sheets) + 1}"
        sheet.save(os.path.join(REPO, f"assets/textures/ui/{name}.png"))
        sheets.append(name)

    lines = [
        "--!strict",
        "-- Generated by tools/textures/pack_icons.py: where each image sits in",
        f"-- assets/textures/ui/{SHEET}*.png (Config/UiImages.Ids). Do not edit.",
        "-- Index i is on Sheets[i // PerSheet + 1], cell i % PerSheet.",
        "",
        "return {",
        f"\tCell = {CELL},",
        f"\tColumns = {COLS},",
        f"\tPerSheet = {per_sheet},",
        "\tSheets = { " + ", ".join(f'"{n}"' for n in sheets) + " } :: { string },",
        "\tIcons = {",
    ]
    for i, name in enumerate(names):
        lines.append(f"\t\t{name} = {i},")
    lines += ["\t} :: { [string]: number },", "}", ""]
    with open(os.path.join(REPO, f"src/shared/Config/{LUA}.luau"), "w", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"Packed {len(names)} images into {', '.join(sheets)}")


main()
